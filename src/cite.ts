// Ссылки на источники в переводе (WP-цитаты). В оригинале (шаблон ACM) ссылки
// вида «[Devlin et al. 2018]» набраны цветом ссылки — глаз пропускает их мимо
// текста. Переверстка теряет этот цвет, и аппарат читается как часть фразы
// («В переводах часто есть источники… чтобы они не выглядели как часть
// текста»). Здесь — ЧИСТЫЙ разборщик: строка абзаца → последовательность
// кусков (обычный текст / ссылка). Рендер у каждого свой: reflow (App.tsx)
// вешает <span class="cite">, экспорт (export.ts) пишет тот же класс в HTML.
//
// Разбор консервативный: сомнительное остаётся обычным текстом. Ложная
// подсветка обычной скобки стоит доверия к странице, пропущенная ссылка стоит
// одного некрашеного «[…]».
//
// Что реально встречается в книге (замер по хранилищу пользователя,
// «advanced information retrieval», 4514 переведённых абзацев, 2225 скобочных
// вставок): 2133 из них содержат год — и почти все они ссылки, в любых видах,
// какие даёт модель:
//   [Salton et al. 1975]            латиница, «et al.»
//   [Wu et al., 2016]               то же с запятой перед годом
//   [Гудман и др., 2016]            кириллица, «и др.» (модель транслитерирует)
//   [Zangerle и Bauer, 2022]        смешанный: латинские фамилии, русский союз
//   [Robertson, 1977] · [Gey 1994]  один автор
//   [2008] · [2019a]                только год (автор — в самом предложении)
//   [Mikolov et al. 2013b]          буквенный суффикс года, латинский и русский
//   [Clarke et al. 2005, 2006]      несколько работ одного автора
//   [A и B, 2015; C и др., 2019]    несколько ссылок через «;»
//   [2008, с. 659]                  с указанием страницы
//   [van Rijsbergen, 1974]          частица в фамилии
//   [Европейская комиссия 2009]     организация вместо автора
// Скобки БЕЗ года (91 штука) — не ссылки: [CLS], [SEP], [0, 1], [s, e],
// [Q1615], [Раунд 1], [раздел 12.4]. Поэтому год (или чисто числовой стиль,
// см. ниже) — обязательное условие.
//
// Числовой стиль «[12]», «[12, 15]», «[3–7]» в этой книге не встречается ни
// разу (все 764 «голые» числа в скобках — годы), но встречается в книгах с
// нумерованной библиографией, поэтому поддержан отдельной веткой. Ноль в
// начале списка запрещён — иначе под него попадают интервалы [0, 1] (10 раз в
// книге), [0, 3], [0, 12].
//
// Круглые скобки «(Salton, 1971)» НЕ разбираются: в книге стиль ACM, и из 88
// скобок с годом ссылочная форма ровно одна, зато обычных полно — «(рисунок
// 2.1)», «(с 2010 по 2011 год)», «(2016–2018 годы)», «(посещено 2 января 2024
// года)». Цена включения — постоянные ложные срабатывания, выгода — одна
// ссылка на книгу. Вложенные в круглые скобки квадратные («(например, LASER
// [Ян и др., 2020])») разбираются как обычно — разборщик смотрит только на
// «[…]».

/** Кусок абзаца: обычный текст либо ссылка на источник (вместе со скобками). */
export type TextRun = { text: string; cite: boolean };

// кандидат: «[…]» без переносов и вложенных скобок; 180 символов — с запасом
// к самой длинной настоящей ссылке в книге (147 символов, четыре работы)
const CAND = /\[[^\][\n]{1,180}\]/gu;
// формулы, URL, разметка, речь — не библиография
const BAD = /[{}|=<>_^$#@*~\\«»?!]|:\/\//u;
const YEAR = /^(?:1[5-9]\d\d|20\d\d)[a-zа-яё]?$/u;
// фамилия: с прописной, либо частица с апострофом перед прописной (д’Алессандро)
const NAME = /^(?:\p{Lu}|\p{Ll}['’](?=\p{Lu}))[\p{L}\p{M}'’.-]*$/u;
const LETTER = /^[a-zа-яё]$/u; // «[2005a,b]» — второй суффикс отдельным токеном
const PAGES = /^\d{1,4}(?:[–—-]\d{1,4})?$/u; // «с. 659», «с. 7–8»
const WORD = /^\p{Ll}[\p{Ll}\p{M}-]+$/u; // строчное слово (в названиях организаций)
// служебные слова внутри ссылки: соединители, «et al.», частицы фамилий
const PARTICLE = new Set([
  "et", "al", "and", "van", "von", "de", "del", "della", "der", "den", "di", "da", "du", "dos",
  "la", "le", "ten", "ter", "of", "for", "the",
  "и", "др", "соавт", "ван", "фон", "дер", "де",
]);
const LOCATOR = new Set(["с", "p", "pp", "стр", "vol", "т"]);
// нумерованный стиль: только положительные числа до 999 (ноль отсекает [0, 1])
const NUMERIC = /^[1-9]\d{0,2}(?:\s*[,;–—-]\s*[1-9]\d{0,2})*$/u;

/**
 * Содержимое скобок (без самих скобок) — библиографическая ссылка?
 * Экспортируется ради тестов; рендерам нужен splitCitations.
 */
export function isCitation(inner: string): boolean {
  const s = inner.trim();
  if (!s || BAD.test(s)) return false;
  if (NUMERIC.test(s)) return true;
  const toks = s.split(/[\s,;]+/).filter(Boolean);
  if (!toks.length || toks.length > 40) return false;
  let years = 0;
  let others = 0; // слова, не опознанные ни как фамилия, ни как служебные
  let firstIsName = false;
  let prevLoc = false;
  let prevYear = false;
  let endsOk = false; // последний токен — год, буквенный суффикс или страница
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    const bare = t.replace(/[.'’]+$/u, "").toLowerCase();
    let loc = false;
    let year = false;
    let known = true;
    if (YEAR.test(t)) {
      years++;
      year = true;
      endsOk = true;
    } else if (NAME.test(t)) {
      endsOk = false;
    } else if (PARTICLE.has(bare)) {
      endsOk = false;
    } else if (LOCATOR.has(bare)) {
      loc = true;
      endsOk = false;
    } else if (prevLoc && PAGES.test(t)) {
      endsOk = true;
    } else if (prevYear && LETTER.test(t)) {
      year = true;
      endsOk = true;
    } else {
      known = false;
      others++;
      endsOk = false;
    }
    if (i === 0 && known && (year || NAME.test(t))) firstIsName = true;
    prevLoc = loc;
    prevYear = year;
  }
  if (!years || !endsOk) return false;
  if (others === 0) return true;
  // Организация вместо автора («[Европейская комиссия 2009]», «[Национальная
  // библиотека Медицины США, 2021]») — одно-два обычных строчных слова внутри
  // имени. Больше двух (или цифры среди них) — это уже фраза в скобках, а не
  // ссылка: «[1–4 фазы тестирования, 2008]» остаётся обычным текстом.
  return (
    firstIsName &&
    others <= 2 &&
    toks.every((t) => YEAR.test(t) || NAME.test(t) || WORD.test(t) || PARTICLE.has(t.replace(/[.'’]+$/u, "").toLowerCase()))
  );
}

/**
 * Абзац → куски. Склейка кусков посимвольно равна исходной строке: смещения
 * совпадают с сохранённым tr (по ним FindBar адресует совпадения).
 */
export function splitCitations(s: string): TextRun[] {
  if (!s.includes("[")) return [{ text: s, cite: false }];
  const runs: TextRun[] = [];
  let last = 0;
  for (const m of s.matchAll(CAND)) {
    // «…Paris_Saint_Germain_F.C.)@[2017, 2023]» (глава о графах знаний) — срок
    // действия факта, а не ссылка: пара годов в скобках, приклеенных к «@».
    // Ссылка всегда отделена от предыдущего слова пробелом или открывающей
    // скобкой, так что проверка «прилипло к @» отсекает интервал целиком и
    // ничего не стоит: на всю книгу это единственный такой случай.
    if (m.index > 0 && s[m.index - 1] === "@") continue;
    if (!isCitation(m[0].slice(1, -1))) continue;
    if (m.index > last) runs.push({ text: s.slice(last, m.index), cite: false });
    runs.push({ text: m[0], cite: true });
    last = m.index + m[0].length;
  }
  if (!runs.length) return [{ text: s, cite: false }];
  if (last < s.length) runs.push({ text: s.slice(last), cite: false });
  return runs;
}

/// Свести набранное в поле с файлом, который поменяли под ним.
///
/// Трёхсторонний свод. `base` — то, что панель в файле последний раз видела
/// (прочитала или записала), `mine` — то, что читатель набрал с тех пор,
/// `disk` — то, что в файле сейчас. Стволом всегда остаётся текст читателя:
/// mergeRecords не переписывает ни одной существующей строки, только заполняет
/// её ПУСТЫЕ поля и дописывает недостающие термины в конец, так что ни один
/// набранный символ не переезжает.
///
/// Отдельно приходится думать ровно об одном — об удалении. Термин, который
/// был в `base` и которого не стало в `mine`, читатель стёр нарочно, и вернуть
/// его из файла значило бы отменить это руками машины. Такие термины из
/// входящих вычёркиваются. Остальное делится надвое: термин, который у
/// читателя есть, — чужому проходу позволено дозаполнить его пустые поля;
/// термин, новый для обеих сторон, — дописывается.
///
/// Цена, названная вслух: удаление РАСПОЗНАЁТСЯ по термину, а не по строке,
/// потому что термин — единственная общая единица у файла, сайдкара и графа
/// (termKey). Читатель, стёрший у строки только определение, получит его
/// обратно, если чужой проход как раз это определение и написал. Потерянное
/// предложение прозы — та потеря, которую в этом проекте уже выбрали как
/// меньшую (glossarygen: неверное определение снимается, термин остаётся).
function merge3(base: string, mine: string, disk: string): string {
  const had = new Set(parseGlossaryText(base).map((r) => termKey(r.term)));
  const has = new Set(parseGlossaryText(mine).map((r) => termKey(r.term)));
  const incoming = parseGlossaryText(disk).filter((r) => {
    const k = termKey(r.term);
    return has.has(k) || !had.has(k);
  });
  return mergeRecords(mine, incoming).text;
}

// ---- aux model --------------------------------------------------------------

const sleep = (ms: number, signal?: AbortSignal) =>
  new Promise<void>((res, rej) => {
    const onAbort = () => {
      clearTimeout(timer);
      rej(new DOMException("aborted", "AbortError"));
    };
    const timer = setTimeout(() => {
      signal?.removeEventListener("abort", onAbort);
      res();
    }, ms);
    signal?.addEventListener("abort", onAbort);
  });

/// Чьим именем эта панель берёт аренду на общий сервер.
///
/// Одно на всю панель и на все её проходы: два прохода одновременно тут не
/// идут (busy запирает ряды), а если бы и шли — имя одно, повторная выдача
/// заменяет запись, и отпустить его достаточно один раз. Соседи по 11545 —
/// «graph» (graphgen) и «style:<путь книги>» (booktranslate).
const AUX_OWNER = "glossary";

// Сколько ждать загрузки весов, прежде чем считать, что сервер не поднимется.
//
// Было 90 с и было верно для 2,7-гигабайтной модели. На 11545 теперь
// Gemma-4-26B-A4B — 14,2 ГБ, и прочитать 14,2 ГБ с холодного дискового кэша
// это не тридцать секунд. (Тут стояло «из которых 13,3 ГБ экспертов уезжают в
// оперативную память (--cpu-moe)». В умолчаниях этого флага больше нет:
// серверы теперь работают по очереди, MoE-модель получает карту целиком, и
// moe_plan (src-tauri/src/lib.rs) оставляет флаг только для карты, которая
// экспертов действительно не вмещает. На число, которое должна покрыть эта
// константа, замена не влияет: его определяет чтение файла, а не то, куда
// потом лягут тензоры.) Нативная сторона отсчитывает свой предел сама:
// AuxState::BOOT_POLLS = 600 полусекундных итераций, то есть 300 с, после
// которых статус становится «dead».
//
// Здесь СТРОГО БОЛЬШЕ — 360 с, — и это не запас на всякий случай, а
// устранение второго независимого секундомера. Поставь их поровну, и загрузка,
// закончившаяся на 299-й секунде, становится монеткой: либо «up», либо наш
// собственный тайм-аут, который уводит проход на путь «модель не установлена»,
// ничего не пишет и врёт про сервер, уже держащий 14,2 ГБ. Настоящий предел
// один и он нативный; этот — только страховка от статуса, который перестал
// приходить вовсе.
const AUX_START_MS = 360_000;

// Поднять общий сервер (Gemma-4-26B-A4B на 11545) на время прогона и взять на
// него аренду. Вне Tauri invoke бросает — тогда за ответ отвечает HTTP-проба
// того же сервера.
//
// Ждём, пока статус не перестанет быть «starting», а не пока не совпадёт с
// одним из двух заранее выписанных слов. Словарь статусов вырос — к «dead» и
// «none» добавились «nomem» (столько оперативной памяти нет, и запускать
// сервер, который будет молотить свопом, отказались), «crashed» (процесс
// поднялся и сам вышел — почти всегда отказ по VRAM) и «noengine», — и каждый
// из них терминален. Список, выписанный по именам, на любом новом слове
// крутился бы до собственного тайм-аута против сервера, который уже никогда не
// ответит; lib.rs (aux_model_status) просит об этом прямым текстом.
//
// Отличие от модалки, из которой это приехало, одно, и оно в том, ЧТО значит
// false. Там ответ «нет модели» означал «переводим терминов основной моделью,
// качество ниже» — молчаливый запасной путь. Здесь его нет: второй, третий и
// новый читающий проход спрашивают у этой модели и без неё не делают ничего,
// поэтому false — это состояние «модель не установлена», названное вслух
// (gl.noAux), с уже сохранёнными на диске терминами и страницами за спиной.
//
// ЦЕНА, названная вслух: «nomem» и «crashed» сейчас печатаются теми же
// словами, что и «none», — «Модель терминов не установлена», — а это неправда
// на машине, где 14,2 ГБ как раз скачаны. Своей строки у них пока нет в
// i18n.ts, а этот файл в i18n не пишет; ключ назван в отчёте пакета.
async function ensureAux(signal: AbortSignal): Promise<boolean> {
  let s: string;
  try {
    s = await invoke<string>("aux_model_start", { owner: AUX_OWNER });
  } catch {
    return isAuxUp();
  }
  const deadline = Date.now() + AUX_START_MS;
  for (;;) {
    if (s === "up" || s === "external") return true;
    if (s !== "starting") return false; // none | noengine | nomem | crashed | dead
    if (Date.now() >= deadline) return false;
    await sleep(1500, signal);
    try {
      s = await invoke<string>("aux_model_status");
    } catch {
      return isAuxUp();
    }
  }
}

/// Отпустить аренду. Своим именем: сервер глушится только когда отпустили
/// ПОСЛЕДНИЙ владелец, поэтому проход графа или правка стиля, идущие рядом,
/// переживут наш finally (lib.rs: aux_model_stop).
const releaseAux = (): void => {
  invoke("aux_model_stop", { owner: AUX_OWNER }).catch(() => {});
};


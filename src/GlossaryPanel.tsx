/** Чем кончилось. Одна запись на проход — отчёт стоит у своей же кнопки. */
type Report =
  | { pass: "mine"; kind: "done"; added: number; updated: number; found: number }
  | {
      pass: "read";
      kind: "done";
      /// Легла ли справка на диск. profileBook пишет файл только при успехе,
      /// поэтому false — это «модель промолчала», а не «прочитали хуже».
      profiled: boolean;
      /// Сколько терминов НАЗВАЛА модель и сколько из них оказались новыми для
      /// файла. Два числа, потому что они расходятся штатно: половину списка
      /// туда уже положил частотный проход, и «названо 18 · добавлен 1» —
      /// честный отчёт о согласии, а не о пустой работе.
      proposed: number;
      added: number;
      /// Сколько строк проход УДАЛИЛ. Третье число, и оно тут не для полноты:
      /// это единственное место, где проход отчитывается о том, что он трогал
      /// файл читателя в обратную сторону. proposeTerms показывает модели
      /// хвост частотного списка и спрашивает про каждую строку, термин ли это
      /// ЭТОЙ книги или пример В ней («dark of the moon», «star wars»,
      /// «False»), и ответы «нет» уходят в saveGlossary.remove — строки
      /// пропадают из .txt. Свернуть это в `added` нельзя: прогон, добавивший
      /// одиннадцать терминов и выкинувший четыре, сделал с файлом две разные
      /// вещи, и вторую видно только если открыть файл и заметить пропажу.
      /// Тем более что вето не помнит: повтор прохода 1 вернёт удалённое, и
      /// читатель должен понимать, откуда строки взялись снова.
      /// (glossarygen.ts, proposeTerms → vetoMinedTail.)
      vetoed: number;
    }
  | {
      pass: "enrich";
      kind: "done";
      enriched: number;
      skipped: number;
      translated: number;
      noTarget: boolean;
    }
  | {
      pass: "validate";
      kind: "done";
      checked: number;
      cleared: number;
      folded: number;
      groups: number;
      aliases: string;
      /// Подтверждённые дубли, которые остались в файле: строки читателя не
      /// сводит никто, и промолчать об этом нельзя — иначе проход выглядит
      /// так, будто он ничего не нашёл, хотя он нашёл и не тронул.
      kept: number;
      keptList: string;
    }
  | { pass: Pass; kind: "stopped" | "silent" | "noTerms" | "noAux" | "failed" | "saveFailed" };

